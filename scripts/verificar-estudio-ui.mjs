// Contratos API y recorridos reales de estudio sobre datos temporales.
import assert from 'node:assert/strict';
import { crearEntorno } from '../servidor/tests/entorno.js';
const { chromium }=await import(process.env.NEXO_PLAYWRIGHT||'playwright');
const e=await crearEntorno('nexo-estudio-ui-');
let browser;
const errores=[];
try{
  const base=new URL((await e.request('/api/sesion')).response.url).origin;
  e.db.exec("UPDATE anuncio_destinatarios SET leido_en=datetime('now')");
  await e.entrar('docente','garcia@sanmartin.nexo.edu');await e.entrar('alumna','julieta@sanmartin.nexo.edu');
  const banco=[{concepto:'Fracción',definicion:'Partes iguales de un total'},{concepto:'Porcentaje',definicion:'Partes de cien'}];
  const mapa=await e.ok('/api/estudio/practicas','docente','POST',{titulo:'Mapa UI',metodo:'conexiones',banco,visibilidad:'institucion'},201);
  const coop=await e.ok('/api/estudio/practicas','docente','POST',{titulo:'Cooperativa UI',metodo:'cooperativa',banco,visibilidad:'institucion'},201);
  const alumna=e.db.prepare("SELECT id FROM usuarios WHERE email='julieta@sanmartin.nexo.edu'").get();
  const sesion=await e.ok(`/api/estudio/practicas/${coop.id}/sesiones`,'docente','POST',{participantes:[alumna.id]},201);
  browser=await chromium.launch({channel:'chrome',headless:true});
  const pagina=async(email)=>{const context=await browser.newContext({viewport:{width:1280,height:900}});const p=await context.newPage();p.on('pageerror',error=>errores.push(error.message));assert.equal((await p.request.post(`${base}/api/sesion`,{data:{email,contrasena:'nexo1234'}})).status(),200);return p;};
  const estudiante=await pagina('julieta@sanmartin.nexo.edu');
  await estudiante.goto(`${base}/estudio/metodos`,{waitUntil:'domcontentloaded'});
  await estudiante.getByRole('textbox',{name:'Título de práctica'}).fill('Banco creado en UI');
  await estudiante.getByRole('textbox',{name:'Concepto',exact:true}).fill('Mitad');
  await estudiante.getByRole('textbox',{name:'Definición comprobable'}).fill('Una de dos partes iguales');
  await estudiante.getByRole('textbox',{name:'Ejemplo resuelto',exact:true}).fill('Media pizza');
  await estudiante.getByRole('textbox',{name:'Pasos resueltos'}).fill('Dividir en dos partes iguales\nTomar una parte');
  await estudiante.getByRole('button',{name:'Agregar concepto',exact:true}).click();
  await estudiante.getByRole('button',{name:'Guardar práctica',exact:true}).click();
  const ficha=estudiante.getByRole('button',{name:/Banco creado en UI/});await ficha.waitFor();
  const propia=e.db.prepare("SELECT id,banco FROM estudio_practicas WHERE titulo='Banco creado en UI'").get();
  assert.equal(JSON.parse(propia.banco)[0].pasosResueltos.length,2);
  await estudiante.getByRole('textbox',{name:'Mi respuesta',exact:true}).fill('Una mitad es una de dos partes iguales.');
  const registrado=estudiante.waitForResponse(r=>r.url().endsWith(`/api/estudio/practicas/${propia.id}/intentos`)&&r.request().method()==='POST');
  await estudiante.getByRole('button',{name:'Correcta y fluida',exact:true}).click();assert.equal((await registrado).status(),201);
  await estudiante.getByRole('button',{name:'Agregar a mi calendario',exact:true}).click();
  await estudiante.getByRole('button',{name:'Calendario vinculado',exact:true}).waitFor();
  await estudiante.goto(`${base}/estudio/metodos?practica=${propia.id}`,{waitUntil:'domcontentloaded'});
  assert.equal(await estudiante.getByRole('button',{name:'Calendario vinculado',exact:true}).isDisabled(),true);
  assert.equal(e.db.prepare('SELECT COUNT(*) AS n FROM estudio_agenda WHERE practica_id=?').get(propia.id).n,1);
  console.log('PASS: banco con ejemplo/pasos, intento y calendario vinculado persisten');
  await estudiante.goto(`${base}/estudio/metodos?practica=${mapa.id}`,{waitUntil:'domcontentloaded'});
  await estudiante.getByRole('textbox',{name:'Justificación de la conexión'}).fill('Se transforma multiplicando por cien');
  await estudiante.getByRole('button',{name:'Agregar conexión',exact:true}).click();
  const guardado=estudiante.waitForResponse(r=>r.url().endsWith(`/api/estudio/practicas/${mapa.id}/mapa`)&&r.request().method()==='PUT');
  await estudiante.getByRole('button',{name:'Guardar mapa',exact:true}).click();assert.equal((await guardado).status(),200);
  await estudiante.reload({waitUntil:'domcontentloaded'});
  await estudiante.getByRole('listitem').filter({hasText:'Fracción → Porcentaje: Se transforma multiplicando por cien'}).waitFor();
  console.log('PASS: mapa conceptual editable guarda vínculos y reaparece al recargar');
  const docente=await pagina('garcia@sanmartin.nexo.edu');
  await docente.goto(`${base}/estudio/metodos?practica=${coop.id}`,{waitUntil:'domcontentloaded'});
  await docente.getByRole('button',{name:`Sesión ${sesion.id}`,exact:true}).click();
  await docente.getByRole('textbox',{name:'Mi aporte cooperativo'}).fill('Una fracción es una parte igual de un total.');
  const explicacion=docente.waitForResponse(r=>r.url().endsWith(`/sesiones/${sesion.id}/aportes`)&&r.request().method()==='POST');
  await docente.getByRole('button',{name:'Enviar aporte de mi turno'}).click();assert.equal((await explicacion).status(),201);
  await estudiante.goto(`${base}/estudio/metodos?practica=${coop.id}`,{waitUntil:'domcontentloaded'});
  await estudiante.getByRole('button',{name:`Sesión ${sesion.id}`,exact:true}).click();
  await estudiante.getByRole('textbox',{name:'Mi aporte cooperativo'}).fill('¿Por qué deben ser partes iguales?');
  const pregunta=estudiante.waitForResponse(r=>r.url().endsWith(`/sesiones/${sesion.id}/aportes`)&&r.request().method()==='POST');
  await estudiante.getByRole('button',{name:'Enviar aporte de mi turno'}).click();assert.equal((await pregunta).status(),201);
  await docente.getByRole('button',{name:'Actualizar sesiones y aportes'}).click();
  await docente.getByRole('textbox',{name:'Mi aporte cooperativo'}).fill('Reviso: deben ser partes iguales para representar la misma unidad.');
  const revision=docente.waitForResponse(r=>r.url().endsWith(`/sesiones/${sesion.id}/aportes`)&&r.request().method()==='POST');
  await docente.getByRole('button',{name:'Enviar aporte de mi turno'}).click();assert.equal((await revision).status(),201);
  await docente.getByRole('button',{name:'Cerrar sesión cooperativa',exact:true}).click();
  await docente.getByRole('textbox',{name:'Mi aporte cooperativo'}).waitFor({state:'hidden'});
  console.log('PASS: dos personas explican, preguntan, revisan por turnos y cierran la sesión');
  await e.ok(`/api/estudio/practicas/${mapa.id}/intentos`,'alumna','POST',{respuesta:'Mi conexión relaciona ambas representaciones.',calidad:2},201);
  await docente.goto(`${base}/estudio/metodos?practica=${mapa.id}`,{waitUntil:'domcontentloaded'});
  await docente.getByText('Seguimiento docente de esta práctica',{exact:true}).click();
  await docente.getByRole('combobox').filter({hasText:'Elegí una persona'}).click();
  const nombreAlumna=e.db.prepare('SELECT nombre FROM usuarios WHERE id=?').get(alumna.id).nombre;
  await docente.getByRole('option',{name:nombreAlumna,exact:true}).click();
  await docente.getByRole('textbox',{name:'Criterio docente',exact:true}).fill('Justificar la representación equivalente');
  await docente.getByRole('textbox',{name:'Devolución docente de estudio'}).fill('Explicá la multiplicación por cien con un caso.');
  const valoracion=docente.waitForResponse(r=>r.url().endsWith(`/api/estudio/practicas/${mapa.id}/evaluaciones`)&&r.request().method()==='PUT');
  await docente.getByRole('button',{name:'Guardar valoración docente',exact:true}).click();assert.equal((await valoracion).status(),200);
  await estudiante.goto(`${base}/estudio/metodos?practica=${mapa.id}`,{waitUntil:'domcontentloaded'});
  await estudiante.getByText('Memoria por concepto y devoluciones',{exact:true}).click();
  await estudiante.getByText(/Docente: para mejorar · Justificar la representación equivalente/).waitFor();
  console.log('PASS: docente revisa evidencia y estudiante recibe criterio/devolución separados de la autoevaluación');
  assert.deepEqual(errores,[],'Sin errores JavaScript');
}finally{await browser?.close();await e.cerrar();}
